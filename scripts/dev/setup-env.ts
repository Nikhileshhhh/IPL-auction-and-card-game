/**
 * pnpm setup:env — create local .env files with freshly generated secrets.
 * Writes /.env (API) and apps/web/.env.local (web server). Both are gitignored.
 * Never overwrites existing files unless --force is passed.
 */
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from '../db/lib';

const force = process.argv.includes('--force');
const secret = (bytes = 32) => randomBytes(bytes).toString('base64url');
const bff = secret();
const csrf = secret();

const api = `# Generated by pnpm setup:env — local development only. Do not commit.
NODE_ENV=development
PORT=4000
LOG_LEVEL=info
DATABASE_URL=postgres://app_runtime:local-dev-only@127.0.0.1:54329/stumps
MIGRATION_DATABASE_URL=postgres://postgres@127.0.0.1:54329/stumps
APP_ORIGIN=http://localhost:3000
ALLOWED_ORIGINS=http://localhost:3000
AUTH_PROVIDER=local
LOCAL_AUTH_JWT_SECRET=${secret(48)}
BFF_SIGNING_KEY=${bff}
ACCESS_CODE_PEPPER_V1=${secret()}
ROOM_PASSWORD_PEPPER_V1=${secret()}
INVITE_LOOKUP_HMAC_KEY=${secret()}
DATA_ENCRYPTION_KEY_V1=${secret()}
`;
const web = `# Generated by pnpm setup:env — local development only. Do not commit.
INTERNAL_API_URL=http://127.0.0.1:4000
APP_ORIGIN=http://localhost:3000
BFF_SIGNING_KEY=${bff}
CSRF_SIGNING_KEY=${csrf}
NEXT_PUBLIC_SOCKET_URL=http://localhost:4000
`;

for (const [file, body] of [
  [join(ROOT, '.env'), api],
  [join(ROOT, 'apps', 'web', '.env.local'), web],
] as const) {
  if (existsSync(file) && !force) {
    console.warn(`skip ${file} (exists; pass --force to regenerate)`);
    continue;
  }
  writeFileSync(file, body, { mode: 0o600 });
  console.warn(`wrote ${file}`);
}
